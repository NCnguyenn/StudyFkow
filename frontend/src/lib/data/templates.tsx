// ─── Helper: TipTap Doc Builder ───────────────────────────────────────────────

const h = (level: number, text: string) => ({
  type: 'heading', attrs: { level }, content: [{ type: 'text', text }],
});
const p = (text?: string) =>
  text ? { type: 'paragraph', content: [{ type: 'text', text }] } : { type: 'paragraph' };
const bold = (label: string, value: string = '') => ({
  type: 'paragraph',
  content: [
    { type: 'text', marks: [{ type: 'bold' }], text: label },
    { type: 'text', text: value },
  ],
});
const italic = (text: string) => ({
  type: 'paragraph',
  content: [{ type: 'text', marks: [{ type: 'italic' }], text }],
});
const hr = () => ({ type: 'horizontalRule' });
const bullet = (...items: string[]) => ({
  type: 'bulletList',
  content: items.map((t) => ({
    type: 'listItem',
    content: [p(t)],
  })),
});
const ordered = (...items: string[]) => ({
  type: 'orderedList',
  content: items.map((t) => ({
    type: 'listItem',
    content: [p(t)],
  })),
});
const tasks = (...items: string[]) => ({
  type: 'taskList',
  content: items.map((t) => ({
    type: 'taskItem',
    attrs: { checked: false },
    content: [p(t)],
  })),
});
const quote = (text: string) => ({
  type: 'blockquote',
  content: [p(text)],
});
const doc = (...blocks: any[]) => ({
  type: 'doc',
  content: [{ type: 'page', content: blocks }],
});

const today = () => new Date().toLocaleDateString('vi-VN');

